class MedicalFixtureEndToEndTests(unittest.TestCase):
    def setUp(self):
        self.agent = _agent()
        self.facts = _facts()
        self.doc = self.agent._assemble_documentation(
            _medical_request(), self.facts, _medical_sections(), used_fallback=False,
        )
        self.rows_by_fr = {row.requirementId: row for row in self.doc.traceabilityMatrix}
        # systemModules and uiScreens are unconditionally renumbered by list
        # position (see _assign_canonical_ids), so look their final ids up
        # by the stable name instead of assuming the fixture's input id.
        self.module_id_by_name = {m.name: m.id for m in self.doc.systemModules}
        self.screen_id_by_name = {s.name: s.screenId for s in self.doc.uiScreens}

    def test_fr01_account_registration_login_minimum_mapping(self):
        row = self.rows_by_fr["FR-01"]
        self.assertEqual(set(row.useCaseIds), {"UC-01", "UC-02", "UC-08"})
        self.assertTrue(set(row.testCaseIds).issuperset({"TC-01", "TC-02", "TC-03", "TC-04", "TC-20"}))

    def test_fr02_symptom_submission_minimum_mapping(self):
        row = self.rows_by_fr["FR-02"]
        self.assertIn("UC-03", row.useCaseIds)
        self.assertIn("TC-05", row.testCaseIds)
        self.assertIn(self.screen_id_by_name["Symptom Entry"], row.screenIds)

    def test_fr03_fastapi_request_minimum_mapping(self):
        row = self.rows_by_fr["FR-03"]
        self.assertTrue({"UC-03", "UC-10"} & set(row.useCaseIds))
        self.assertIn("API-01", row.apiIds)
        self.assertIn("TC-06", row.testCaseIds)

    def test_fr04_urgency_classification_minimum_mapping(self):
        row = self.rows_by_fr["FR-04"]
        self.assertTrue({"UC-03", "UC-10"} & set(row.useCaseIds))
        self.assertIn(self.module_id_by_name["ClassificationModule"], row.moduleIds)
        self.assertIn("ENT-03", row.entityIds)
        self.assertIn("TC-07", row.testCaseIds)

    def test_fr05_specialist_recommendation_minimum_mapping(self):
        row = self.rows_by_fr["FR-05"]
        self.assertTrue({"UC-03", "UC-09", "UC-10"} & set(row.useCaseIds))
        self.assertIn(self.module_id_by_name["RecommendationModule"], row.moduleIds)
        self.assertIn("TC-08", row.testCaseIds)

    def test_fr07_symptom_history_minimum_mapping(self):
        row = self.rows_by_fr["FR-07"]
