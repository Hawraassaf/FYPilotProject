class RemovedRequirementNeverRemappedTests(unittest.TestCase):
    def test_dangling_reference_to_a_removed_fr_is_dropped_not_remapped(self):
        requirement_ids = {"FR-01", "FR-02"}  # FR-99 no longer exists
        uc = UseCaseDto(id="UC-03", title="x", actor="Patient", goal="", relatedRequirements=["FR-99"])
        test = TestCaseDto(id="TC-01", title="t", type="Unit", expectedResult="r", relatedRequirements=["FR-99"])
        mod = ModuleDto(id="MOD-01", name="x", responsibility="", relatedRequirements=["FR-99"])

        _agent()._reconcile_requirement_references(requirement_ids, [uc], [], [mod], [test])

        # Never silently remapped to "FR-01" (the first sorted id) -- simply dropped.
        self.assertEqual(uc.relatedRequirements, [])
        self.assertEqual(test.relatedRequirements, [])
        self.assertEqual(mod.relatedRequirements, [])
        self.assertNotIn("FR-01", uc.relatedRequirements)


