class ReverseReferenceRebuildTests(unittest.TestCase):
    def test_reverse_use_case_and_module_ids_rebuilt_from_child_links(self):
        fr = RequirementDto(id="FR-02", title="Symptom Submission", description="", priority="High", source="s")
        uc = UseCaseDto(id="UC-03", title="Submit Symptoms", actor="Patient", goal="", relatedRequirements=["FR-02"])
        mod = ModuleDto(id="MOD-02", name="SymptomIntakeModule", responsibility="", relatedRequirements=["FR-02"])

        _agent()._rebuild_requirement_reverse_references([fr], [], [uc], [mod])

        self.assertEqual(fr.relatedUseCaseIds, ["UC-03"])
        self.assertEqual(fr.relatedModuleIds, ["MOD-02"])

    def test_stale_reverse_reference_is_replaced_not_preserved(self):
        """fr.relatedUseCaseIds starts out pointing at a use case that does
        NOT actually reference this FR (e.g. leftover from the requirements
        section's own independent, now-untrustworthy guess) -- the rebuild
        must overwrite it with the real child-derived answer, never merge
        with or preserve the stale value."""
        fr = RequirementDto(
            id="FR-02", title="Symptom Submission", description="", priority="High", source="s",
            relatedUseCaseIds=["UC-99"],  # stale / never real
        )
        uc_real = UseCaseDto(id="UC-03", title="Submit Symptoms", actor="Patient", goal="", relatedRequirements=["FR-02"])

        _agent()._rebuild_requirement_reverse_references([fr], [], [uc_real], [])

        self.assertEqual(fr.relatedUseCaseIds, ["UC-03"])
        self.assertNotIn("UC-99", fr.relatedUseCaseIds)


