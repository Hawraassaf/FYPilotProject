class RegistryContentTests(unittest.TestCase):
    def test_registry_preserves_exact_fr_ids_and_titles(self):
        frs = [
            RequirementDto(id="FR-01", title="Patient Account Registration and Login", description="", priority="High", source="s"),
            RequirementDto(id="FR-02", title="Symptom Description Submission", description="", priority="High", source="s"),
        ]
        nfrs = [
            RequirementDto(id="NFR-01", title="Triage Response Time", description="", priority="High", source="s"),
        ]

        registry = _agent()._build_requirements_registry(frs, nfrs)

        self.assertEqual(registry.ids, frozenset({"FR-01", "FR-02", "NFR-01"}))
        titles_by_id = {e.id: e.title for e in registry.entries}
        self.assertEqual(titles_by_id["FR-01"], "Patient Account Registration and Login")
        self.assertEqual(titles_by_id["FR-02"], "Symptom Description Submission")
        self.assertEqual(titles_by_id["NFR-01"], "Triage Response Time")


