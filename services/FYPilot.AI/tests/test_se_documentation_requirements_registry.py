class DependentPromptInjectionTests(unittest.TestCase):
    def test_dependent_prompts_contain_the_immutable_registry(self):
        facts = _facts()
        registry = RequirementsRegistry(entries=(
            RequirementsRegistryEntry(
                id="FR-02", title="Symptom Description Submission", description="",
                priority="High", sourceClassification="confirmed",
            ),
        ))

        prompts = _agent()._build_section_prompts("CONTEXT", facts, registry=registry)

        for key in ("useCases", "modulesArchitecture", "database", "uiApi", "testingSecurity"):
            prompt_text, _ = prompts[key]
            self.assertIn("FR-02 | Symptom Description Submission", prompt_text)
            self.assertIn("THESE IDS ARE IMMUTABLE", prompt_text)
            self.assertIn("Never redefine an id", prompt_text)

    def test_requirements_and_ai_report_prompts_never_receive_the_registry(self):
        facts = _facts()
        registry = RequirementsRegistry(entries=(
            RequirementsRegistryEntry(
                id="FR-02", title="Symptom Description Submission", description="",
                priority="High", sourceClassification="confirmed",
            ),
        ))

        prompts = _agent()._build_section_prompts("CONTEXT", facts, registry=registry)

        self.assertNotIn("THESE IDS ARE IMMUTABLE", prompts["requirements"][0])

    def test_fr02_cannot_be_redefined_as_login_when_registry_says_symptom_submission(self):
        """The registry's rendering is the ONLY place a dependent prompt
        learns what FR-02 means -- it appears exactly once, with the
        canonical title, so nothing in the prompt text itself offers a
        conflicting definition for the model to "choose" instead."""
        registry = RequirementsRegistry(entries=(
            RequirementsRegistryEntry(
                id="FR-02", title="Symptom Description Submission", description="",
                priority="High", sourceClassification="confirmed",
            ),
        ))

        rendered = registry.render_compact()

        self.assertEqual(rendered.count("FR-02"), 1)
        self.assertIn("FR-02 | Symptom Description Submission", rendered)
        self.assertNotIn("Login", rendered)


