class NoPositionalMappingTests(unittest.TestCase):
    def test_matrix_never_links_by_list_position_or_matching_number(self):
        """FR-02 is the SECOND fr; UC-02 is the SECOND use case -- if the
        builder ever fell back to positional/index matching, FR-02 would
        pick up UC-02 despite UC-02 declaring a completely different FR."""
        fr01 = RequirementDto(id="FR-01", title="Login", description="", priority="High", source="s")
        fr02 = RequirementDto(id="FR-02", title="Symptom Submission", description="", priority="High", source="s")
        uc01 = UseCaseDto(id="UC-01", title="Login", actor="Patient", goal="", relatedRequirements=["FR-01"])
        uc02 = UseCaseDto(id="UC-02", title="Logout", actor="Patient", goal="", relatedRequirements=["FR-01"])  # NOT FR-02, despite matching position

        rows = _agent()._build_traceability([fr01, fr02], [], [uc01, uc02], [], [], [], [], [])

        fr02_row = next(r for r in rows if r.requirementId == "FR-02")
        self.assertEqual(fr02_row.useCaseIds, [])
        self.assertNotIn("UC-02", fr02_row.useCaseIds)


