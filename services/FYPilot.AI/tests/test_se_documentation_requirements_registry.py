class PerDimensionReferenceTests(unittest.TestCase):
    def setUp(self):
        self.agent = _agent()
        self.fr02 = RequirementDto(id="FR-02", title="Symptom Description Submission", description="", priority="High", source="s")
        self.fr07 = RequirementDto(id="FR-07", title="Symptom Submission History", description="", priority="Medium", source="s")

    def _row_for(self, fr, **kwargs):
        defaults = dict(use_cases=[], modules=[], entities=[], tests=[], ui_screens=[], api_points=[])
        defaults.update(kwargs)
        rows = self.agent._build_traceability(
            [self.fr02, self.fr07], [],
            defaults["use_cases"], defaults["modules"], defaults["entities"],
            defaults["tests"], defaults["ui_screens"], defaults["api_points"],
        )
        return next(r for r in rows if r.requirementId == fr.id)

    def test_use_case_references_correct_fr(self):
        uc = UseCaseDto(id="UC-03", title="Submit Symptoms", actor="Patient", goal="", relatedRequirements=["FR-02"])
        row = self._row_for(self.fr02, use_cases=[uc])
        self.assertEqual(row.useCaseIds, ["UC-03"])

    def test_module_references_correct_fr(self):
        mod = ModuleDto(id="MOD-02", name="SymptomIntakeModule", responsibility="", relatedRequirements=["FR-02"])
        row = self._row_for(self.fr02, modules=[mod])
        self.assertEqual(row.moduleIds, ["MOD-02"])

    def test_entity_references_correct_fr(self):
        ent = EntityDto(entityId="ENT-02", name="TriageSession", purpose="", relatedRequirementIds=["FR-02"])
        row = self._row_for(self.fr02, entities=[ent])
        self.assertEqual(row.entityIds, ["ENT-02"])

    def test_ui_screen_references_correct_fr(self):
        screen = UiScreenDto(screenId="UI-02", name="Symptom Entry", relatedRequirements=["FR-02"])
        row = self._row_for(self.fr02, ui_screens=[screen])
        self.assertEqual(row.screenIds, ["UI-02"])

    def test_api_references_correct_fr(self):
        from app.agents.se_documentation.se_documentation_orchestrator import ApiPointDto
        api = ApiPointDto(
            apiId="API-01", name="Triage API", method="POST", endpoint="/triage",
            purpose="", requestSummary="", responseSummary="", relatedRequirements=["FR-02"],
        )
        row = self._row_for(self.fr02, api_points=[api])
        self.assertEqual(row.apiIds, ["API-01"])

    def test_test_case_references_correct_fr(self):
        test = TestCaseDto(id="TC-05", title="Symptom submission positive", type="Integration", expectedResult="Saved", relatedRequirements=["FR-02"])
        row = self._row_for(self.fr02, tests=[test])
        self.assertEqual(row.testCaseIds, ["TC-05"])


